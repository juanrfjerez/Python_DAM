# Ejercicio11: Dibuja un ordinograma de un programa que muestre los números pares comprendidos
# entre el 1 y el 200. Para ello utiliza un contador y suma de 2 en 2

# Inicializamos el contador en 2, que es el primer número par mayor que 1
contador = 2

# Mientras el contador sea menor o igual a 200
while contador <= 200:
    print(contador)
    contador += 2  # Sumamos de 2 en 2 para obtener solo pares